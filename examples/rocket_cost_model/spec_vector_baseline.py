"""Build or validate private SPEC roles 1-3 for Rocket plus Saturn research.

All three roles use unchanged licensed SPEC source. Roles 1 and 2 are frozen
baselines; role 3 selects an immutable Saturn-aware compiler candidate. Licensed
files and generated outputs remain outside the repository. QEMU is only a
correctness gate and never supplies a Saturn performance result.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import shlex
import subprocess


BENCHMARK = "648.exchange2_s"
GENERATED = "# Generated by spec_vector_baseline.py; private research config.\n"
ROLES = ("1-scalar", "2-generic-vector", "3-saturn-aware")
SCALAR_FLAGS = (
    "-march=rv64gc -mabi=lp64d -mtune=rocket "
    "-fno-tree-loop-vectorize -fno-tree-slp-vectorize"
)
VECTOR_FLAGS = (
    "-march=rv64gcv_zvbb -mabi=lp64d -mtune=rocket "
    "-mrvv-vector-bits=zvl -fvect-cost-model=dynamic -fopt-info-vec-all"
)


def sha256(path: Path) -> str:
    """Return the SHA-256 identity of one compiler, config, or emulator."""
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def candidate_name(value: str) -> str:
    """Validate a role-3 identity before using it in a SPEC label or path."""
    if not re.fullmatch(r"[0-9a-f]{12,32}", value):
        raise ValueError("candidate ID must be a 12-32 digit lowercase hexadecimal prefix")
    return value


def role_settings(role: str, candidate_id: str | None = None) -> tuple[str, str, bool]:
    """Return the private config label, target flags, and vector-QEMU selector."""
    if role == "1-scalar":
        if candidate_id:
            raise ValueError("role 1 does not accept a candidate ID")
        return "saturn_role1_scalar", SCALAR_FLAGS, False
    if role == "2-generic-vector":
        if candidate_id:
            raise ValueError("role 2 does not accept a candidate ID")
        return "saturn_role2_generic_vector", VECTOR_FLAGS, True
    if role == "3-saturn-aware":
        if not candidate_id:
            raise ValueError("role 3 requires an immutable candidate ID")
        return f"saturn_role3_{candidate_name(candidate_id)}", VECTOR_FLAGS, True
    raise ValueError(f"unknown experiment role: {role}")


def render_config(template: str, label: str, target_flags: str, qemu: Path,
                  vector_qemu: bool) -> str:
    """Render a SPEC config with fixed flags and a functional QEMU launcher."""
    if not re.fullmatch(r"[a-z0-9][a-z0-9_]{0,63}", label):
        raise ValueError("invalid SPEC config label")
    if not qemu.is_absolute() or not re.fullmatch(r"/[\w./-]+", str(qemu)):
        raise ValueError("QEMU must have an absolute path without shell metacharacters")
    if "\n" in target_flags or "\r" in target_flags:
        raise ValueError("target flags must fit on one config line")

    replacements = (
        (r"(?m)^%define label riscv\b[^\n]*$", f"%define label {label}"),
        (r"(?m)^%\s+define model\s+-march=rv64imafdc\s+-mabi=lp64d[^\n]*$",
         f"%   define model      {target_flags}"),
        (r"(?m)^ignore_errors\s*=\s*1\s*$", "ignore_errors        = 0"),
    )
    config = template
    for pattern, replacement in replacements:
        config, count = re.subn(pattern, replacement, config)
        if count != 1:
            raise ValueError(f"expected exactly one config match for {pattern!r}, got {count}")

    cpu = " -cpu rv64,v=true,vlen=128,elen=64" if vector_qemu else ""
    return (
        GENERATED + config + "\ndefault:\n"
        "   use_submit_for_speed = yes\n"
        f"   submit = {qemu}{cpu} ${{command}}\n"
    )


def validated(log: str, benchmark: str, size: str) -> bool:
    """Require SPEC's explicit success line for the selected benchmark/input."""
    return bool(re.search(
        rf"(?m)^ Success {re.escape(benchmark)} base {re.escape(size)}\b", log
    ))


def validate_candidate_manifest(manifest: dict, candidate_id: str, gcc_root: Path) -> None:
    """Bind a role-3 label to its full content identity and compiler prefix."""
    full_id = manifest.get("candidate_id")
    if not isinstance(full_id, str) or not re.fullmatch(r"[0-9a-f]{64}", full_id) \
            or not full_id.startswith(candidate_id):
        raise ValueError("candidate manifest identity does not match --candidate-id")
    prefix = manifest.get("prefix")
    if not isinstance(prefix, str) or Path(prefix).resolve() != gcc_root:
        raise ValueError("candidate manifest prefix does not match --gcc-root")
    if manifest.get("gcc_revision") != "1b306039ac49f8ad91ca71d3de3150a3c9fa792a":
        raise ValueError("candidate manifest does not use the pinned GCC 15 revision")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--spec-dir", type=Path, required=True)
    parser.add_argument("--gcc-root", type=Path, required=True)
    parser.add_argument("--speckle", type=Path, required=True)
    parser.add_argument("--qemu", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--role", choices=ROLES, required=True)
    parser.add_argument("--candidate-id")
    parser.add_argument("--candidate-manifest", type=Path)
    parser.add_argument("--benchmark", default=BENCHMARK)
    parser.add_argument("--size", choices=("test", "train"), default="test")
    parser.add_argument("--action", choices=("build", "validate"), required=True)
    args = parser.parse_args()

    if not re.fullmatch(r"[56]\d{2}\.[A-Za-z0-9_]+_[rs]", args.benchmark):
        parser.error("--benchmark must be a SPEC CPU2017 benchmark name")
    try:
        label, target_flags, vector_qemu = role_settings(args.role, args.candidate_id)
    except ValueError as exc:
        parser.error(str(exc))
    if args.role == "3-saturn-aware" and args.candidate_manifest is None:
        parser.error("role 3 requires --candidate-manifest")
    if args.role != "3-saturn-aware" and args.candidate_manifest is not None:
        parser.error("only role 3 accepts --candidate-manifest")

    spec_dir = args.spec_dir.resolve()
    gcc_root = args.gcc_root.resolve()
    qemu = args.qemu.resolve()
    output = args.out.resolve()
    template = args.speckle.resolve() / "riscv.cfg"
    compiler = gcc_root / "bin/riscv64-unknown-linux-gnu-gcc"
    prerequisites = [spec_dir / "shrc", spec_dir / "bin/runcpu", template, compiler, qemu]
    candidate_manifest = None
    if args.candidate_manifest is not None:
        candidate_manifest = args.candidate_manifest.resolve()
        prerequisites.append(candidate_manifest)
    for path in prerequisites:
        if not path.is_file():
            parser.error(f"missing prerequisite: {path}")
    if candidate_manifest is not None:
        try:
            validate_candidate_manifest(
                json.loads(candidate_manifest.read_text()), args.candidate_id, gcc_root,
            )
        except (json.JSONDecodeError, ValueError) as exc:
            parser.error(str(exc))

    output.mkdir(mode=0o700, parents=True, exist_ok=True)
    config = spec_dir / "config" / f"{label}.cfg"
    desired = render_config(template.read_text(), label, target_flags, qemu, vector_qemu)
    if config.exists() and not config.read_text().startswith(GENERATED):
        parser.error(f"refusing to replace a config not generated by this script: {config}")
    config.write_text(desired)

    command = [
        "bash", "-c", ". ./shrc && exec runcpu " + " ".join(
            shlex.quote(item) for item in (
                "--verbose=10", f"--config={config.name}", f"--size={args.size}",
                f"--action={args.action}", "--define=build_ncpus=2", args.benchmark,
            )
        ),
    ]
    stem = f"{args.benchmark}-{args.size}-{label}-{args.action}"
    log = output / f"{stem}.log"
    metadata = {
        "benchmark": args.benchmark,
        "size": args.size,
        "role": args.role,
        "candidate_id": args.candidate_id,
        "action": args.action,
        "source_variant": "unchanged SPEC CPU2017 source",
        "target_flags": target_flags,
        "compiler_role": {
            "1-scalar": "frozen scalar reference",
            "2-generic-vector": "frozen stock-GCC RVV baseline",
            "3-saturn-aware": "iterative Saturn-aware cost-model candidate",
        }[args.role],
        "gcc_version": subprocess.check_output([compiler, "--version"], text=True).splitlines()[0],
        "gcc_sha256": sha256(compiler),
        "candidate_manifest": str(candidate_manifest) if candidate_manifest else None,
        "candidate_manifest_sha256": sha256(candidate_manifest) if candidate_manifest else None,
        "config": str(config),
        "config_sha256": sha256(config),
        "qemu": str(qemu),
        "qemu_sha256": sha256(qemu),
        "command": command,
        "log": str(log),
        "qemu_correctness_only": True,
        "target_performance_result": False,
    }
    (output / f"{stem}.json").write_text(json.dumps(metadata, indent=2) + "\n")

    environment = os.environ.copy()
    environment["RISCV"] = str(gcc_root)
    environment.pop("LD_PRELOAD", None)
    with log.open("w") as stream:
        result = subprocess.run(
            command, cwd=spec_dir, env=environment, stdout=stream,
            stderr=subprocess.STDOUT, check=False,
        )
    print(f"runcpu exit={result.returncode}; log={log}")
    if result.returncode:
        return result.returncode
    if args.action == "validate" and not validated(log.read_text(), args.benchmark, args.size):
        print("SPEC did not report the required success result; inspect the private log")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
