"""Generate a GCC RISC-V DFA (boom.md) and riscv_tune_param suggestions from
the extracted hardware model.  Output is a drop-in replacement for the
scheduling_description() text in CHIA's chia/chipyard/boom_model.py (same
tune name "boom", same (eq_attr "tune" "boom") guard)."""
import re

from . import muldiv_model as mdm
from . import timing

# GCC insn types per reservation class.  Every scalar type of GCC 15.1
# riscv.md is covered (gcc_assert(insn_has_dfa_reservation_p) in
# riscv_sched_variable_issue); 'ghost' is exempt (returns before the assert).
SCALAR_CLASSES = {
    "alu": "unknown,const,arith,logical,shift,slt,move,nop,multi,sfb_alu,bitmanip,rotate,"
           "min,max,minu,maxu,clz,ctz,cpop,condmove,zicond,mvpair,clmul,crypto",
    "branch": "branch",
    "jump": "jump,jalr,ret,call,auipc",
    "csr": "rdfrm,wrfrm,wrvxrm,rdvlenb,rdvl,trap,vsetvl,vsetvl_pre",
    "imul": "imul",
    "load": "load",
    "fpload": "fpload",
    "store": "store",
    "fpstore": "fpstore",
    "atomic": "atomic",
    "fp": "fadd,fmul,fmadd,fmove,fcvt",
    "f2i": "mfc,fcmp,fcvt_f2i",
    "i2f": "mtc,fcvt_i2f",
    "fdiv": "fdiv",
    "fsqrt": "fsqrt",
}


def gcc_types_from_md(riscv_md_text):
    m = re.search(r'\(define_attr "type"\s*"([^"]+)"', riscv_md_text, re.S)
    return [t.strip() for t in m.group(1).replace("\n", " ").split(",") if t.strip()]


def dfa_values(model, idiv_policy="full_width_div10"):
    rows, extra = timing.class_table(model)
    by = {r["cls"]: r for r in rows}
    if idiv_policy == "full_width_div10":
        di = timing.div_core_latency(mdm.FN_DIVU, 1, 0xF123_4567_89AB_CDEF, 10)
        si = timing.div_core_latency(mdm.FN_DIV, 0, 0x7123_4567, 10)
    elif idiv_policy == "worst":
        di = si = timing.div_core_latency(mdm.FN_DIV, 1, (-5) & timing.M64, 13)
    else:
        raise ValueError(idiv_policy)
    return {
        "alu": 1, "branch": 1, "jump": by["auipc"]["latency"], "csr": 4,
        "imul": by["imul"]["latency"], "idiv_si": si, "idiv_di": di,
        "load": by["load_int"]["latency"], "fpload": by["load_fp"]["latency"],
        "store": 1, "fpstore": 1, "atomic": by["load_int"]["latency"],
        "fp": by["fp_fma"]["latency"], "f2i": by["fp_to_int"]["latency"],
        "i2f": by["int_to_fp"]["latency"], "fdiv": by["fdiv"]["latency"],
        "fsqrt": by["fsqrt"]["latency"],
        "fdiv_occ": by["fdiv"]["recip_thpt"], "fsqrt_occ": by["fsqrt"]["recip_thpt"],
        "idiv_si_occ": si, "idiv_di_occ": di,
    }


def generate_dfa(model, gcc_types=None, tune="boom", idiv_policy="full_width_div10"):
    v = dfa_values(model, idiv_policy)
    ports = model["exec_ports"]
    ints = [p["port"] for p in ports["int"]]
    mems = [p["port"] for p in ports["mem"]]
    fps = [p["port"] for p in ports["fp"]]
    u = lambda p: f"boom_{p}"
    pool = lambda ps: "(" + "|".join(u(p) for p in ps) + ")" if len(ps) > 1 else u(ps[0])
    one = lambda fu: [p["port"] for p in ports["int"] if fu in p["fus"]][0]
    fp_f2i = [p["port"] for p in ports["fp"] if any("F2I" in f for f in p["fus"])][0]
    fp_div = [p["port"] for p in ports["fp"] if any("FDIV" in f for f in p["fus"])][0]
    alu_ports = [p["port"] for p in ports["int"] if "ALU" in p["fus"]]

    L = [";; Generated by rtl-model/boomhw from BOOM v3 / rocket-chip Scala sources",
         ";; (MegaBoomV3Config). Latency = issue -> dependent issue (cycles).",
         ";; Do not edit by hand; regenerate with: python3 -m boomhw.cli",
         ";; Port map: " + "; ".join(f"{p['port']}={'+'.join(p['fus'])}" for p in ports["int"]),
         ";; idiv policy: " + idiv_policy + " (operand-dependent on hardware, see hw model)",
         "",
         '(define_automaton "boom_int,boom_mem,boom_fp,boom_idiv_auto,boom_fdiv_auto")']
    for p in ints:
        L.append(f'(define_cpu_unit "{u(p)}" "boom_int")')
    for p in mems:
        L.append(f'(define_cpu_unit "{u(p)}" "boom_mem")')
    for p in fps:
        L.append(f'(define_cpu_unit "{u(p)}" "boom_fp")')
    L.append('(define_cpu_unit "boom_idiv" "boom_idiv_auto")')
    L.append('(define_cpu_unit "boom_fdiv" "boom_fdiv_auto")')
    L.append("")

    def resv(name, lat, types, res, mode=None, comment=None):
        cond = f'(eq_attr "type" "{types}")'
        if mode:
            cond = f'(and {cond} (eq_attr "mode" "{mode}"))'
        if comment:
            L.append(f";; {comment}")
        L.append(f'(define_insn_reservation "boom_{name}" {lat}\n'
                 f'  (and (eq_attr "tune" "{tune}")\n       {cond})\n  "{res}")\n')

    C = SCALAR_CLASSES
    resv("alu", v["alu"], C["alu"], pool(alu_ports), comment="any of the 4 integer ALUs; fast wakeup")
    resv("branch", v["branch"], C["branch"], pool(alu_ports),
         comment="conditional branches are FU_ALU and resolve on any ALU")
    resv("jump", v["jump"], C["jump"], u(one("JMP")),
         comment="FU_JMP (jal/jalr/auipc) only on int0; not bypassable -> slow wakeup")
    resv("csr", v["csr"], C["csr"], u(one("CSR")), comment="CSR unit on int1 (serializing); latency estimate")
    resv("imul", v["imul"], C["imul"], u(one("IMUL")),
         comment="pipelined multiplier (imulLatency=3) on int2, one per cycle; incl. mulh/mulhu")
    resv("idiv_si", v["idiv_si"], C.get("idiv", "idiv"),
         f"{u(one('IDIV'))}+boom_idiv,boom_idiv*{v['idiv_si_occ'] - 1}", mode="SI",
         comment="iterative MulDiv on int3; only the issue slot of int3 is taken, its ALU stays free")
    resv("idiv_di", v["idiv_di"], "idiv",
         f"{u(one('IDIV'))}+boom_idiv,boom_idiv*{v['idiv_di_occ'] - 1}", mode="DI")
    resv("load", v["load"], C["load"], pool(mems), comment="L1 hit, speculative wakeup from s1")
    resv("fpload", v["fpload"], C["fpload"], pool(mems), comment="FP loads: no speculative wakeup")
    resv("store", v["store"], C["store"], pool(mems))
    resv("fpstore", v["fpstore"], C["fpstore"], f"{pool(mems)}+{u(fp_f2i)}",
         comment="FP store data goes through the FPIU on fp0")
    resv("atomic", v["atomic"], C["atomic"], pool(mems), comment="latency estimate")
    resv("fp", v["fp"], C["fp"], pool(fps), comment="FMA pipes on both FP ports, no FP bypass")
    resv("f2i", v["f2i"], C["f2i"], u(fp_f2i), comment="FP->int (FPIU) only on fp0; latency estimate")
    resv("i2f", v["i2f"], C["i2f"], u(one("I2F")), comment="int->FP (IFPU) on integer port int0; latency estimate")
    resv("fdiv", v["fdiv"], C["fdiv"], f"{u(fp_div)}+boom_fdiv,boom_fdiv*{v['fdiv_occ'] - 1}",
         comment="hardfloat DivSqrtRecF64 on fp0, one op at a time")
    resv("fsqrt", v["fsqrt"], C["fsqrt"], f"{u(fp_div)}+boom_fdiv,boom_fdiv*{v['fsqrt_occ'] - 1}")
    if gcc_types:
        covered = set()
        for t in list(C.values()) + ["idiv"]:
            covered.update(x.strip() for x in t.split(","))
        rest = [t for t in gcc_types if t not in covered and t != "ghost"]
        if rest:
            resv("unsupported", 1, ",".join(rest), u(ints[0]),
                 comment="types BOOM v3 cannot execute (vector etc.); present only for reservation coverage")
    return "\n".join(L), v


def tune_suggestion(model, anish_seed=None):
    rows, extra = timing.class_table(model)
    by = {r["cls"]: r for r in rows}
    v = dfa_values(model)
    sug = {
        "fp_add": {"rtl_latency": by["fp_fma"]["latency"], "suggest": [by["fp_fma"]["latency"]] * 2,
                   "why": "FADD/FMUL/FMA dependent latency = 2 (issue->EX) + dfmaLatency 4 + 1 (writeback wakeup)"},
        "fp_mul": {"rtl_latency": by["fp_fma"]["latency"], "suggest": [by["fp_fma"]["latency"]] * 2,
                   "why": "same FMA pipe as fp_add"},
        "fp_div": {"rtl_latency": by["fdiv"]["latency"], "suggest": [by["fdiv"]["latency"]] * 2,
                   "why": "hardfloat DivSqrtRecF64 18 cycles (unit-RTL) + BOOM wrapper/pipeline; SF runs as DF"},
        "int_mul": {"rtl_latency": by["imul"]["latency"], "suggest": [by["imul"]["latency"]] * 2,
                    "why": "pipelined, 1/cycle on int2; dependent latency 6 (multiplier result uses slow wakeup). "
                           "This cost steers synth_mult (shift/add vs mul) and the const-div mulh sequence cost"},
        "int_div": {"rtl_latency": {"SI": v["idiv_si"], "DI": v["idiv_di"], "range": "7..71"},
                    "suggest": [v["idiv_si"], v["idiv_di"]],
                    "why": "GCC compares this against the multiply-high sequence for x/const. "
                           "Hardware: early-out iterative divider, 64-bit datapath for W ops too"},
        "issue_rate": {"rtl": model["core"]["decodeWidth"]["value"], "suggest": model["core"]["decodeWidth"]["value"],
                       "why": "decode/rename/dispatch width 4"},
        "branch_cost": {"rtl_mispredict_penalty_estimate": by["branch_mispredict_penalty"]["latency"],
                        "suggest": "search 6..12 (Anish's F2 winner 12 is consistent with a ~13-cycle penalty)",
                        "why": "GCC branch_cost is a relative heuristic, not the penalty itself"},
        "memory_cost": {"rtl_load_use": by["load_int"]["latency"], "suggest": 5,
                        "why": "load-use 4 on hit; keep rocket's 5 pending measurement"},
        "fmv_cost": {"rtl": {"int_to_fp": by["int_to_fp"]["latency"], "fp_to_int": by["fp_to_int"]["latency"]},
                     "suggest": 8, "why": "GPR<->FPR moves 6/8 cycles (estimate), both single-ported (int0 / fp0)"},
        "slow_unaligned_access": {"suggest": True, "why": "BOOM LSU raises misaligned exceptions (trap + emulation)",
                                  "src": model["anchors"]["ld_misalign"]["src"]},
        "use_divmod_expansion": {"suggest": True,
                                 "why": "one non-pipelined divider; x%y as x-(x/y)*y costs mul(6)+sub(1) instead of a second 7..71-cycle divide"},
        "fusible_ops": {"suggest": "RISCV_FUSE_NOTHING", "why": "BOOM v3 decode has no macro-op fusion"},
        "march": {"suggest": "rv64imafdc_zicsr_zifencei", "why": "useZba/useZbb/useZbs/useConditionalZero = false; DTS isa "
                  + str(model.get("dts", {}).get("isa"))},
    }
    if anish_seed:
        for k, val in anish_seed.items():
            if k in sug:
                sug[k]["anish_seed"] = val
    lines = ["/* Generated from rtl-model hardware model (MegaBoomV3Config). */",
             "static const struct riscv_tune_param boom_tune_info = {"]
    f = lambda k: ", ".join(f"COSTS_N_INSNS ({x})" for x in sug[k]["suggest"])
    lines += [f"  {{{f('fp_add')}}},\t/* fp_add */", f"  {{{f('fp_mul')}}},\t/* fp_mul */",
              f"  {{{f('fp_div')}}},\t/* fp_div */", f"  {{{f('int_mul')}}},\t/* int_mul */",
              f"  {{{f('int_div')}}},\t/* int_div */", f"  {sug['issue_rate']['suggest']},\t/* issue_rate */",
              "  3,\t/* branch_cost: SEARCH (see json) */", f"  {sug['memory_cost']['suggest']},\t/* memory_cost */",
              f"  {sug['fmv_cost']['suggest']},\t/* fmv_cost */", "  true,\t/* slow_unaligned_access */",
              "  false,\t/* vector_unaligned_access */", "  true,\t/* use_divmod_expansion */",
              "  false,\t/* overlap_op_by_pieces */", "  RISCV_FUSE_NOTHING,\t/* fusible_ops */",
              "  NULL,\t/* vector cost */", "  NULL,\t/* function_align */", "  NULL,\t/* jump_align */",
              "  NULL,\t/* loop_align */", "};"]
    return sug, "\n".join(lines) + "\n"
