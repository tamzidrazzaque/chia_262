"""Build or validate one private SPEC CPU2017 benchmark with a fixed RISC-V ISA.

The installed SPEC tree and all licensed outputs stay outside this repository.
For validation, SPEC runs its normal result checks through QEMU user mode.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import shlex
import subprocess
from pathlib import Path


TUNES = ("rocket", "generic-ooo", "xiangshan-nanhu")
GENERATED = "# Generated by spec_cpu2017_local.py; private experiment config.\n"


def render_config(template: str, tune: str, qemu: Path) -> str:
    """Change only target ISA/ABI, tune, label, and QEMU launch settings."""
    if tune not in TUNES:
        raise ValueError(f"Unsupported experiment tune: {tune}")
    if not qemu.is_absolute() or not re.fullmatch(r"/[\w./-]+", str(qemu)):
        raise ValueError("QEMU must have an absolute path without shell metacharacters")

    changes = (
        (r"(?m)^%define label riscv\b[^\n]*$", f"%define label riscv_{tune.replace('-', '_')}"),
        (r"(?m)^%\s+define model\s+-march=rv64imafdc\s+-mabi=lp64d[^\n]*$",
         "%   define model      -march=rv64gc -mabi=lp64d"),
    )
    config = template
    for pattern, replacement in changes:
        config, count = re.subn(pattern, replacement, config)
        if count != 1:
            raise ValueError(f"Expected exactly one config match for {pattern!r}, got {count}")
    for compiler in ("CC", "CXX", "FC"):
        pattern = rf"(?m)^(\s*{compiler}\s*=\s*\$\(SPECLANG\)riscv64-unknown-linux-gnu-[^\n]+)$"
        config, count = re.subn(pattern, lambda m: m[1].rstrip() + f" -mtune={tune}", config)
        if count != 1:
            raise ValueError(f"Expected one {compiler} definition, got {count}")
    return GENERATED + config + f"\ndefault:\n   submit = {qemu} ${{command}}\n"


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def validated(log: str, benchmark: str, size: str) -> bool:
    """Require SPEC's explicit correctness result, not only runcpu's exit code."""
    return bool(re.search(rf"(?m)^ Success {re.escape(benchmark)} base {re.escape(size)}\b", log))


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--spec-dir", type=Path, required=True)
    parser.add_argument("--gcc-root", type=Path, required=True)
    parser.add_argument("--speckle", type=Path, required=True)
    parser.add_argument("--qemu", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--tune", choices=TUNES, required=True)
    parser.add_argument("--benchmark", default="505.mcf_r")
    parser.add_argument("--size", choices=("test", "train", "ref"), default="test")
    parser.add_argument("--action", choices=("build", "validate"), default="build")
    args = parser.parse_args()

    if not re.fullmatch(r"[56]\d{2}\.[A-Za-z0-9_]+_[rs]", args.benchmark):
        parser.error("--benchmark must be a SPEC CPU2017 benchmark name")
    spec_dir = args.spec_dir.resolve()
    gcc_root = args.gcc_root.resolve()
    qemu = args.qemu.resolve()
    out = args.out.resolve()
    template = args.speckle.resolve() / "riscv.cfg"
    compiler = gcc_root / "bin/riscv64-unknown-linux-gnu-gcc"
    for path in (spec_dir / "shrc", spec_dir / "bin/runcpu", template, compiler, qemu):
        if not path.is_file():
            parser.error(f"Missing prerequisite: {path}")
    out.mkdir(parents=True, exist_ok=True)
    config = spec_dir / "config" / f"riscv_{args.tune.replace('-', '_')}.cfg"
    desired = render_config(template.read_text(), args.tune, qemu)
    if config.exists() and not config.read_text().startswith(GENERATED):
        parser.error(f"Refusing to replace a config not generated by this script: {config}")
    config.write_text(desired)

    command = ["bash", "-c", ". ./shrc && exec runcpu "
               + " ".join(shlex.quote(item) for item in (
                   "--verbose=10", f"--config={config.name}", f"--size={args.size}",
                   f"--action={args.action}", "--define=build_ncpus=2", args.benchmark))]
    log = out / f"{args.benchmark}-{args.size}-{args.tune}-{args.action}.log"
    metadata = {
        "benchmark": args.benchmark, "size": args.size, "tune": args.tune,
        "action": args.action, "spec_dir": str(spec_dir), "gcc_root": str(gcc_root),
        "gcc_version": subprocess.check_output([compiler, "--version"], text=True).splitlines()[0],
        "gcc_sha256": sha256(compiler), "config": str(config), "config_sha256": sha256(config),
        "qemu": str(qemu), "qemu_sha256": sha256(qemu), "command": command,
        "log": str(log),
    }
    (out / f"{args.benchmark}-{args.size}-{args.tune}-{args.action}.json").write_text(
        json.dumps(metadata, indent=2) + "\n"
    )
    env = os.environ.copy()
    env["RISCV"] = str(gcc_root)
    with log.open("w") as stream:
        result = subprocess.run(command, cwd=spec_dir, env=env, stdout=stream,
                                stderr=subprocess.STDOUT, check=False)
    print(f"runcpu exit={result.returncode}; log={log}")
    if result.returncode:
        return result.returncode
    if args.action == "validate" and not validated(log.read_text(), args.benchmark, args.size):
        print("SPEC did not report a matching Success result; inspect the validation log")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
